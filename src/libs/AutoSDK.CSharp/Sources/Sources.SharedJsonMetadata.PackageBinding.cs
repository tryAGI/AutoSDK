using System.Reflection;
using AutoSDK.Models;

namespace AutoSDK.Generation;

public static partial class Sources
{
    private static FileWithName CreateSharedJsonMetadataPackageBinding()
    {
        // MinVer stamps every package in this release with this same normalized NuGet version.
        // Keep the analyzer build-only; consumer projects never inherit Roslyn or STJ tooling.
        var informationalVersion = typeof(Sources).Assembly
            .GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion
            ?? throw new InvalidOperationException("AutoSDK package version is unavailable.");
        var version = informationalVersion.Split('+')[0];
        return new FileWithName("AutoSDK.SharedJsonMetadata.props", $@"<!-- Auto-generated by AutoSDK. Regenerate with the matching CLI/analyzer release. -->
<Project>
  <PropertyGroup>
    <AutoSDKJsonMetadataVersion>{version}</AutoSDKJsonMetadataVersion>
    <AutoSDKJsonMetadataManifestVersion>{Internal.SharedJsonMetadataProtocol.CurrentVersion}</AutoSDKJsonMetadataManifestVersion>
  </PropertyGroup>
</Project>");
    }
}
